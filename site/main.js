function readPreference(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}

function savePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Rendering works without persistence. */ }
}

function detectLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  if (urlLang && Object.hasOwn(translations, urlLang)) return urlLang;

  const saved = readPreference('avocook-lang');
  if (saved && Object.hasOwn(translations, saved)) return saved;

  const browser = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  return Object.hasOwn(translations, browser) ? browser : 'fr';
}

function applyLanguage(lang) {
  if (!Object.hasOwn(translations, lang)) return;
  const t = translations[lang];

  document.documentElement.lang = lang;
  document.title = t.meta_title;
  document.querySelector('meta[name="description"]').setAttribute('content', t.meta_description);
  document.querySelector('meta[property="og:title"]').setAttribute('content', t.meta_title);
  document.querySelector('meta[property="og:description"]').setAttribute('content', t.meta_description);
  document.getElementById('lang-selector').setAttribute('aria-label', t.language_label);
  document.getElementById('theme-toggle').setAttribute('aria-label', t.theme_label);
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    el.alt = t[el.getAttribute('data-i18n-alt')];
  });
  document.querySelectorAll('[data-privacy-link]').forEach(el => {
    const path = lang === 'en' ? 'PRIVACY.md' : `docs/${lang}/PRIVACY.md`;
    el.href = `https://github.com/Logarex/AvoCook/blob/main/${path}`;
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('[data-i18n-img]').forEach(el => {
    const template = el.getAttribute('data-i18n-img');
    el.onload = () => {
      el.style.display = '';
      if (el.nextElementSibling) el.nextElementSibling.style.display = 'none';
    };
    el.onerror = () => {
      el.style.display = 'none';
      if (el.nextElementSibling) el.nextElementSibling.style.display = 'flex';
    };
    // No Danish screenshots are bundled; use the existing English images.
    el.src = template.replace('{lang}', lang === 'da' ? 'en' : lang);
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const selected = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', selected);
    btn.setAttribute('aria-pressed', String(selected));
  });

  savePreference('avocook-lang', lang);
}

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  const btn = document.getElementById('theme-toggle');
  if (btn) btn.textContent = '◑';
  savePreference('avocook-theme', theme);
}

function initTheme() {
  const saved = readPreference('avocook-theme');
  if (saved === 'light' || saved === 'dark') { applyTheme(saved); return; }
  const preferred = window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
  applyTheme(preferred);
}

function initScrollAnimations() {
  if (!('IntersectionObserver' in window)) {
    document.querySelectorAll('.fade-up').forEach(el => el.classList.add('visible'));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0, rootMargin: '0px 0px -32px 0px' });

  document.querySelectorAll('.fade-up').forEach(el => observer.observe(el));
}

function initNav() {
  const nav = document.getElementById('main-nav');
  if (!nav) return;
  const onScroll = () => nav.classList.toggle('scrolled', window.scrollY > 24);
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
}

function initCarousel() {
  const track = document.getElementById('carousel');
  if (!track) return;

  let isDown = false, startX = 0, scrollLeft = 0;

  track.addEventListener('mousedown', e => {
    isDown = true;
    startX = e.pageX - track.offsetLeft;
    scrollLeft = track.scrollLeft;
  });
  track.addEventListener('mouseleave', () => { isDown = false; });
  track.addEventListener('mouseup', () => { isDown = false; });
  track.addEventListener('mousemove', e => {
    if (!isDown) return;
    e.preventDefault();
    const x = e.pageX - track.offsetLeft;
    track.scrollLeft = scrollLeft - (x - startX) * 1.4;
  });
}

document.addEventListener('DOMContentLoaded', () => {
  initTheme();
  applyLanguage(detectLanguage());
  initScrollAnimations();
  initNav();
  initCarousel();

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      applyLanguage(lang);
      const url = new URL(window.location.href);
      url.searchParams.set('lang', lang);
      window.history.replaceState(null, '', url);
    });
  });

  const themeBtn = document.getElementById('theme-toggle');
  if (themeBtn) {
    themeBtn.addEventListener('click', () => {
      const current = document.documentElement.getAttribute('data-theme');
      applyTheme(current === 'dark' ? 'light' : 'dark');
    });
  }

  const dlBtn = document.getElementById('nav-download-btn');
  const dlWrap = dlBtn ? dlBtn.closest('.nav-download-wrap') : null;
  if (dlBtn && dlWrap) {
    dlBtn.addEventListener('click', () => {
      const open = dlWrap.classList.toggle('open');
      dlBtn.setAttribute('aria-expanded', String(open));
    });
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && dlWrap.classList.contains('open')) {
        dlWrap.classList.remove('open');
        dlBtn.setAttribute('aria-expanded', 'false');
        dlBtn.focus();
      }
    });
    document.addEventListener('click', (e) => {
      if (!dlWrap.contains(e.target)) {
        dlWrap.classList.remove('open');
        dlBtn.setAttribute('aria-expanded', 'false');
      }
    });
  }

  const emailLink = document.getElementById('contact-email-link');
  if (emailLink) {
    const parts = ['avocook', 'nephoos', 'com'];
    const addr = parts[0] + '@' + parts[1] + '.' + parts[2];
    emailLink.href = 'mail\u0074o:' + addr;
    emailLink.textContent = addr;
  }
});
