function readPreference(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}

function savePreference(key, value) {
  try { localStorage.setItem(key, value); } catch { /* storage blocked */ }
}

function detectLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  if (urlLang && Object.hasOwn(translations, urlLang)) return urlLang;

  const saved = readPreference('avocook-lang');
  if (saved && Object.hasOwn(translations, saved)) return saved;

  const browser = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  return Object.hasOwn(translations, browser) ? browser : 'en';
}

function applyLanguage(lang) {
  if (!Object.hasOwn(translations, lang)) return;
  const t = translations[lang];

  document.documentElement.lang = lang;
  document.title = t.meta_title;
  document.querySelector('meta[name="description"]').setAttribute('content', t.meta_description);
  document.querySelector('meta[property="og:title"]').setAttribute('content', t.meta_title);
  document.querySelector('meta[property="og:description"]').setAttribute('content', t.meta_description);
  document.getElementById('lang-selector').setAttribute('aria-label', t.language_label);
  document.getElementById('theme-toggle').setAttribute('aria-label', t.theme_label);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    el.alt = t[el.getAttribute('data-i18n-alt')];
  });

  document.querySelectorAll('[data-privacy-link]').forEach(el => {
    const path = lang === 'en' ? 'PRIVACY.md' : `docs/${lang}/PRIVACY.md`;
    el.href = `https://github.com/Logarex/AvoCook/blob/main/${path}`;
  });

  document.querySelectorAll('[data-i18n-img]').forEach(el => {
    const template = el.getAttribute('data-i18n-img');
    el.onload = () => {
      el.style.display = '';
      if (el.nextElementSibling) el.nextElementSibling.style.display = 'none';
    };
    el.onerror = () => {
      el.style.display = 'none';
      if (el.nextElementSibling) el.nextElementSibling.style.display = 'flex';
    };
    el.src = template.replace('{lang}', lang);
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const selected = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', selected);
    btn.setAttribute('aria-pressed', String(selected));
  });

  savePreference('avocook-lang', lang);
}

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  savePreference('avocook-theme', theme);
}

function initTheme() {
  const saved = readPreference('avocook-theme');
  if (saved === 'light' || saved === 'dark') { applyTheme(saved); return; }
  const dark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  document.documentElement.setAttribute('data-theme', dark ? 'dark' : 'light');
}

document.addEventListener('DOMContentLoaded', () => {
  initTheme();
  applyLanguage(detectLanguage());

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      applyLanguage(lang);
      const url = new URL(window.location.href);
      url.searchParams.set('lang', lang);
      window.history.replaceState(null, '', url);
    });
  });

  document.getElementById('theme-toggle').addEventListener('click', () => {
    const current = document.documentElement.getAttribute('data-theme');
    applyTheme(current === 'dark' ? 'light' : 'dark');
  });

  const emailLink = document.getElementById('contact-email-link');
  const parts = ['avocook', 'nephoos', 'com'];
  const address = `${parts[0]}@${parts[1]}.${parts[2]}`;
  emailLink.href = `mail${'to'}:${address}`;
  emailLink.textContent = address;
});
